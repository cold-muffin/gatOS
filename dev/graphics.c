#define GFX_FONT_UNITS 2048
#define GFX_FONT_ASCENT 1854

/* Intermediate curves are computed in floating point to retain small-size detail. */
static int gfx_scaled_x(int font_x, int origin, int size) {
    return origin + iround((double)font_x * size / GFX_FONT_UNITS);
}
static int gfx_scaled_y(int font_y, int origin, int size) {
    return origin + iround((double)(GFX_FONT_ASCENT - font_y) * size / GFX_FONT_UNITS);
}
int graphics_draw_char(char ascii, int x, int y, int size, uint8_t color) {
    unsigned int ch = (unsigned char)ascii;
    if (size <= 0) return 0;
    if (ch < 32 || ch > 126) ch = '?';
    GfxGlyph glyph = gfx_font_glyphs[ch - 32];
    int cx=0, cy=0, sx=0, sy=0;
    for (unsigned int i = glyph.offset; i < (unsigned int)glyph.offset + glyph.count; ++i) {
        const GfxFontCommand *cmd = &gfx_font_commands[i];
        int nx, ny;
        switch (cmd->kind) {
            case 0:
                cx=cmd->p[0]; cy=cmd->p[1]; sx=cx; sy=cy;
                break;
            case 1:
                nx=cmd->p[0]; ny=cmd->p[1];
                gfx_line(gfx_scaled_x(cx,x,size),gfx_scaled_y(cy,y,size),
                         gfx_scaled_x(nx,x,size),gfx_scaled_y(ny,y,size),color);
                cx=nx; cy=ny;
                break;
            case 2:
                nx=cmd->p[2]; ny=cmd->p[3];
                gfx_quad_bezier(gfx_scaled_x(cx,x,size),gfx_scaled_y(cy,y,size),
                                gfx_scaled_x(cmd->p[0],x,size),gfx_scaled_y(cmd->p[1],y,size),
                                gfx_scaled_x(nx,x,size),gfx_scaled_y(ny,y,size),color);
                cx=nx; cy=ny;
                break;
            case 3:
                nx=cmd->p[4]; ny=cmd->p[5];
                gfx_cubic_bezier(gfx_scaled_x(cx,x,size),gfx_scaled_y(cy,y,size),
                                 gfx_scaled_x(cmd->p[0],x,size),gfx_scaled_y(cmd->p[1],y,size),
                                 gfx_scaled_x(cmd->p[2],x,size),gfx_scaled_y(cmd->p[3],y,size),
                                 gfx_scaled_x(nx,x,size),gfx_scaled_y(ny,y,size),color);
                cx=nx; cy=ny;
                break;
            case 4:
                if (cx!=sx || cy!=sy)
                    gfx_line(gfx_scaled_x(cx,x,size),gfx_scaled_y(cy,y,size),
                             gfx_scaled_x(sx,x,size),gfx_scaled_y(sy,y,size),color);
                cx=sx; cy=sy;
                break;
        }
    }
    return iround((double)glyph.advance * size / GFX_FONT_UNITS);
}
void graphics_draw_text(const char *text, int x, int y, int size, uint8_t color) {
    if (!text || size <= 0) return;
    int start=x;
    for (; *text; ++text) {
        if (*text == '\n') { x=start; y += size * 6 / 5; }
        else if (*text == '\r') { }
        else if (*text == '\t') { x += 4 * iround((double)gfx_font_glyphs[0].advance * size / GFX_FONT_UNITS); }
        else x += graphics_draw_char(*text, x, y, size, color);
    }
}
