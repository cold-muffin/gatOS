/* Freestanding 2D wireframe primitives for 32-bit gatOS, VGA mode 12h.
   Bresenham-style line/ellipse adapted from ideas in:
   https://gist.github.com/bert/1085538
   No heap, matrix code, SDL, or libm needed. */
#include "graphics.h"
#include "vga.h"

#define GFX_WIDTH 640
#define GFX_HEIGHT 480

static int iabs(int x) { return x < 0 ? -x : x; }
static int iround(double v) { return (int)(v >= 0 ? v + 0.5 : v - 0.5); }
static int max(int a, int b) { return a > b ? a : b; }

static void pixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < GFX_WIDTH && y >= 0 && y < GFX_HEIGHT)
        vga_set_pixel(color, (size_t)x, (size_t)y);
}

void gfx_line(int x0, int y0, int x1, int y1, uint8_t color) {
    int dx = iabs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -iabs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (;;) {
        pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

/* x0,y0 and x1,y1 are opposite rectangle corners. */
void gfx_rect(int x0, int y0, int x1, int y1, uint8_t color) {
    gfx_line(x0, y0, x1, y0, color);
    gfx_line(x1, y0, x1, y1, color);
    gfx_line(x1, y1, x0, y1, color);
    gfx_line(x0, y1, x0, y0, color);
}

/* Bresenham midpoint ellipse enclosed by opposite corners. */
void gfx_ellipse(int x0, int y0, int x1, int y1, uint8_t color) {
    int a = iabs(x1 - x0), b = iabs(y1 - y0);
    if (a == 0 || b == 0) { gfx_line(x0, y0, x1, y1, color); return; }
    int b1 = b & 1;
    long long dx = 4LL * (1 - a) * b * b;
    long long dy = 4LL * (b1 + 1) * a * a;
    long long err = dx + dy + (long long)b1 * a * a;
    long long e2;
    if (x0 > x1) { int t=x0; x0=x1; x1=t; }
    if (y0 > y1) { int t=y0; y0=y1; y1=t; }
    y0 += (b + 1) / 2;
    y1 = y0 - b1;
    a *= 8 * a;
    b1 = 8 * b * b;
    do {
        pixel(x1, y0, color);
        pixel(x0, y0, color);
        pixel(x0, y1, color);
        pixel(x1, y1, color);
        e2 = 2 * err;
        if (e2 >= dx) { ++x0; --x1; err += dx += b1; }
        if (e2 <= dy) { ++y0; --y1; err += dy += a; }
    } while (x0 <= x1);
    while (y0 - y1 < b) {
        pixel(x0 - 1, y0, color);
        pixel(x1 + 1, y0++, color);
        pixel(x0 - 1, y1, color);
        pixel(x1 + 1, y1--, color);
    }
}

void gfx_circle(int cx, int cy, int radius, uint8_t color) {
    if (radius < 0) return;
    gfx_ellipse(cx - radius, cy - radius,
                cx + radius, cy + radius, color);
}

/* Curve evaluation followed by short Bresenham segments.
   Fixed step count is simple and predictable for a kernel. */
void gfx_quad_bezier(int x0, int y0, int cx, int cy,
                     int x1, int y1, uint8_t color) {
    int steps = (max(iabs(cx-x0), iabs(cy-y0)) +
                 max(iabs(x1-cx), iabs(y1-cy))) / 3;
    if (steps < 16) steps = 16;
    if (steps > 2048) steps = 2048;
    int px=x0, py=y0;
    for (int i=1; i<=steps; ++i) {
        double t=(double)i/steps, u=1.0-t;
        int x=iround(u*u*x0+2.0*u*t*cx+t*t*x1);
        int y=iround(u*u*y0+2.0*u*t*cy+t*t*y1);
        gfx_line(px,py,x,y,color);
        px=x; py=y;
    }
}

void gfx_cubic_bezier(int x0, int y0, int c1x, int c1y,
                      int c2x, int c2y, int x1, int y1,
                      uint8_t color) {
    int steps = (max(iabs(c1x-x0), iabs(c1y-y0)) +
                 max(iabs(c2x-c1x), iabs(c2y-c1y)) +
                 max(iabs(x1-c2x), iabs(y1-c2y))) / 3;
    if (steps < 24) steps = 24;
    if (steps > 2048) steps = 2048;
    int px=x0, py=y0;
    for (int i=1; i<=steps; ++i) {
        double t=(double)i/steps, u=1.0-t;
        int x=iround(u*u*u*x0 + 3*u*u*t*c1x + 3*u*t*t*c2x + t*t*t*x1);
        int y=iround(u*u*u*y0 + 3*u*u*t*c1y + 3*u*t*t*c2y + t*t*t*y1);
        gfx_line(px,py,x,y,color);
        px=x; py=y;
    }
}


